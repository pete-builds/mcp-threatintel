"""Ahmia.fi dark web search client.

Ahmia indexes .onion sites and provides a clearnet search interface.
No JSON API exists, so we scrape HTML results. This is fragile by nature
but it's the only free dark web search option.

No API key required.

Failure contract: when Ahmia cannot be searched (network error, non-200,
a redirect, or a page that is not a results page), search() returns a dict
with "available": False and an "error" string, never an empty result list.
An empty list means Ahmia answered and genuinely had no matches.

Known upstream change (October 2026): Ahmia's search form now carries a
hidden field whose name and value are generated by the homepage, and a
search without it is redirected (302) to "/". Ahmia's robots.txt also
disallows /search/ for all user agents, so this client does not scrape the
token; it reports the index as unavailable instead.
"""

import logging
import re
from urllib.parse import unquote

import httpx

from .base import BaseClient

logger = logging.getLogger("threatintel.ahmia")

#: Present on every real Ahmia results page, including one with zero matches.
RESULTS_PAGE_MARKER = 'id="ahmiaResultsPage"'

SOURCE = "ahmia.fi (dark web)"


class AhmiaUnavailable(Exception):
    """Ahmia could not be searched; the message says why."""


def _unavailable(query: str, reason: str) -> dict:
    """Structured error that cannot be mistaken for an empty search."""
    return {
        "query": query,
        "source": SOURCE,
        "available": False,
        "error": (
            f"Dark web index unavailable: {reason}. "
            "No search was performed, so this is NOT a clean result."
        ),
    }


class AhmiaClient(BaseClient):
    """Ahmia.fi dark web search via HTML scraping."""

    def __init__(self):
        super().__init__("https://ahmia.fi", rate_limit=2.0)

    async def search(self, query: str, max_results: int = 20) -> dict:
        """Search the dark web via Ahmia.

        Args:
            query: Search terms.
            max_results: Max results to return (default 20).

        Returns:
            Dict with results containing title, url (.onion), and description.
        """
        await self._rate_limit()
        try:
            html = await self._fetch_results_page(query)
        except AhmiaUnavailable as exc:
            logger.warning("ahmia: query=%r unavailable: %s", query, exc)
            return _unavailable(query, str(exc))

        results = _parse_results(html, max_results)
        logger.info("ahmia: query=%r results=%d", query, len(results))

        return {
            "query": query,
            "source": SOURCE,
            "result_count": len(results),
            "results": results,
        }

    async def _fetch_results_page(self, query: str) -> str:
        """Return the HTML of a real results page or raise AhmiaUnavailable.

        Transport errors get one retry. Redirects are not followed: Ahmia
        answers a search it will not serve with a 302 to its homepage, and
        following it would parse the homepage as "no results".
        """
        url = f"{self.base_url}/search/"
        reason = "request failed"
        for _attempt in range(2):
            try:
                resp = await self._client.get(url, params={"q": query})
            except httpx.HTTPError as exc:
                reason = f"request to ahmia.fi failed ({type(exc).__name__})"
                continue
            if resp.is_redirect:
                location = resp.headers.get("location", "")
                raise AhmiaUnavailable(
                    f"ahmia.fi redirected the search (HTTP {resp.status_code} "
                    f"to {location!r}), which it does when a request lacks "
                    "its search-form token"
                )
            if resp.status_code != 200:
                raise AhmiaUnavailable(f"ahmia.fi returned HTTP {resp.status_code}")
            if RESULTS_PAGE_MARKER not in resp.text:
                raise AhmiaUnavailable(
                    "ahmia.fi returned a page that is not a search results page"
                )
            return resp.text
        raise AhmiaUnavailable(reason)


def _parse_results(html: str, max_results: int) -> list[dict]:
    """Parse Ahmia search results from HTML.

    Ahmia results are in <li class="result"> elements containing:
    - <a> with href (the .onion URL, often via redirect)
    - <h4> or heading with title
    - <p> or description text
    """
    results = []

    # Only look inside the results list, so filter menus and page chrome
    # never parse as results. No fallback to "any link on the page": that
    # turned non-results pages into plausible-looking hits or a false empty.
    list_match = re.search(
        r'<ol[^>]*class="[^"]*searchResults[^"]*"[^>]*>(.*?)</ol>', html, re.DOTALL
    )
    if list_match:
        html = list_match.group(1)

    result_blocks = re.findall(
        r'<li[^>]*class="[^"]*result[^"]*"[^>]*>(.*?)</li>',
        html,
        re.DOTALL,
    )

    for block in result_blocks:
        if len(results) >= max_results:
            break

        # Extract URL (may be a redirect URL containing the .onion)
        href_match = re.search(r'href="([^"]+)"', block)
        title_match = re.search(r'<h4[^>]*>(.*?)</h4>', block, re.DOTALL)
        if not title_match:
            title_match = re.search(r'<a[^>]*>([^<]+)</a>', block)
        desc_match = re.search(r'<p[^>]*>(.*?)</p>', block, re.DOTALL)

        if not href_match:
            continue

        href = href_match.group(1)
        onion_url = _extract_onion_url(href)
        title = _clean_html(title_match.group(1)) if title_match else ""
        description = _clean_html(desc_match.group(1)) if desc_match else ""

        if onion_url or href:
            results.append({
                "title": title,
                "url": onion_url or href,
                "description": description,
            })

    return results


def _extract_onion_url(href: str) -> str | None:
    """Extract .onion URL from an Ahmia redirect link or direct link."""
    # Ahmia wraps result links in /search/redirect?...&redirect_url=<onion>
    # (older pages used search_url=).
    if "redirect" in href:
        match = re.search(r'(?:redirect_url|search_url)=([^&]+)', href)
        if match:
            return unquote(match.group(1))

    # Direct .onion link
    if ".onion" in href:
        return href

    return None


def _clean_html(text: str) -> str:
    """Strip HTML tags and clean whitespace."""
    text = re.sub(r'<[^>]+>', '', text)
    text = re.sub(r'\s+', ' ', text)
    return text.strip()
